CREATE FUNCTION union_private.staff_scope_guard() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,union_private AS $$
BEGIN
 IF NEW.role <> 'admin' AND NOT EXISTS(SELECT 1 FROM union_private.showrooms WHERE id=NEW.showroom_id) THEN RAISE EXCEPTION 'invalid staff showroom'; END IF;
 IF NEW.role = 'admin' AND NEW.showroom_id <> '' THEN RAISE EXCEPTION 'invalid global owner scope'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER staff_scope_guard BEFORE INSERT OR UPDATE OF role,showroom_id ON union_private.staff FOR EACH ROW EXECUTE FUNCTION union_private.staff_scope_guard();

-- A showroom row lock serializes reservations across all server instances.
-- These are database guards; availability displayed in the browser is advisory.
CREATE FUNCTION union_private.booking_guard() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,union_private AS $$
DECLARE s union_private.showrooms%ROWTYPE; e union_private.staff%ROWTYPE; total integer;
BEGIN
 IF TG_OP='INSERT' THEN
  SELECT * INTO s FROM union_private.showrooms WHERE id=NEW.showroom_id FOR UPDATE;
  IF NOT FOUND OR s.active<>1 OR NEW.duration_minute<>s.booking_duration_minute OR NEW.slot_index>s.teams_count
   OR NEW.start_minute<s.work_start_minute OR NEW.start_minute+NEW.duration_minute>s.work_end_minute
   OR (NEW.start_minute-s.work_start_minute)%s.booking_duration_minute<>0
   OR NOT (s.work_days::jsonb @> jsonb_build_array(EXTRACT(DOW FROM NEW.booking_date::date)::integer))
   OR (NEW.service_mode='home' AND s.home_service_enabled<>1) OR (NEW.service_mode='shop' AND s.shop_service_enabled<>1)
   OR NOT EXISTS(SELECT 1 FROM union_private.request_types WHERE id=NEW.request_type_id AND showroom_id=s.id AND published=1)
  THEN RAISE EXCEPTION 'showroom schedule changed'; END IF;
  SELECT count(*) INTO total FROM union_private.bookings WHERE showroom_id=s.id AND booking_date=NEW.booking_date AND status NOT IN('cancelled','rejected');
  IF total>=s.daily_booking_limit THEN RAISE EXCEPTION 'daily limit reached'; END IF;
  IF EXISTS(SELECT 1 FROM union_private.bookings WHERE showroom_id=s.id AND booking_date=NEW.booking_date AND slot_index=NEW.slot_index AND status NOT IN('cancelled','rejected') AND start_minute<NEW.start_minute+NEW.duration_minute AND start_minute+duration_minute>NEW.start_minute)
   THEN RAISE EXCEPTION 'time unavailable'; END IF;
 END IF;
 IF NEW.assigned_staff_id IS NOT NULL AND (TG_OP='INSERT' OR NEW.assigned_staff_id IS DISTINCT FROM OLD.assigned_staff_id) THEN
  SELECT * INTO e FROM union_private.staff WHERE id=NEW.assigned_staff_id FOR UPDATE;
  IF NOT FOUND OR e.active<>1 OR e.deleted_at IS NOT NULL OR e.role<>'employee' OR e.showroom_id<>NEW.showroom_id THEN RAISE EXCEPTION 'employee capacity unavailable'; END IF;
  SELECT * INTO s FROM union_private.showrooms WHERE id=NEW.showroom_id;
  SELECT count(*) INTO total FROM union_private.bookings WHERE assigned_staff_id=e.id AND booking_date=NEW.booking_date AND id<>NEW.id AND status NOT IN('cancelled','rejected');
  IF total>=s.employee_daily_limit OR EXISTS(SELECT 1 FROM union_private.bookings WHERE assigned_staff_id=e.id AND booking_date=NEW.booking_date AND id<>NEW.id AND status NOT IN('cancelled','rejected') AND start_minute<NEW.start_minute+NEW.duration_minute AND start_minute+duration_minute>NEW.start_minute)
  THEN RAISE EXCEPTION 'employee capacity unavailable'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER booking_guard BEFORE INSERT OR UPDATE OF assigned_staff_id ON union_private.bookings FOR EACH ROW EXECUTE FUNCTION union_private.booking_guard();

-- Prevent a settings edit from racing an insert and reducing reserved team capacity.
CREATE FUNCTION union_private.schedule_guard() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,union_private AS $$
BEGIN
 IF NEW.teams_count < OLD.teams_count AND EXISTS(SELECT 1 FROM union_private.bookings WHERE showroom_id=NEW.id AND booking_date>=(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Amman')::date::text AND status NOT IN('cancelled','rejected') AND slot_index>NEW.teams_count) THEN RAISE EXCEPTION 'reserved team capacity'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER schedule_guard BEFORE UPDATE OF teams_count ON union_private.showrooms FOR EACH ROW EXECUTE FUNCTION union_private.schedule_guard();

